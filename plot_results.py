#!/usr/bin/env python3
"""
plot_results.py
Visualization Script for Population Genetics Analysis

This script generates visualizations from the population genetics analysis output:
1. PCA Scatter Plot by Super Population (PC1 vs PC2, colored by super_pop)
2. PCA Scatter Plot by Detailed Population (PC1 vs PC2, colored by pop - 26 populations)
3. ADMIXTURE Bar Plot for K=5 (stacked bar chart, sorted by super_pop and pop)

Input Files:
    - PCA file: results/chr22_pca.eigenvec (generated by PLINK)
    - Admixture file: results/chr22_pruned.5.Q (K=5 ancestry proportions)
    - Metadata: integrated_call_samples_v3.20130502.ALL.panel (tab-separated)
        - Contains 'pop' (26 populations like CHB, YRI, CEU)
        - Contains 'super_pop' (5 groups: AFR, AMR, EAS, EUR, SAS)

Output Files:
    - results/pca_super_pop.png (PCA colored by super population)
    - results/pca_detailed_pop.png (PCA colored by 26 detailed populations)
    - results/admixture_k5_sorted.png (ADMIXTURE sorted by super_pop and pop)

Requirements:
    - pandas
    - matplotlib
    - seaborn
"""

import os
import sys
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
import numpy as np


# Define super population colors as a constant
SUPER_POP_COLORS = {
    'AFR': '#E41A1C',  # Red
    'EUR': '#377EB8',  # Blue
    'EAS': '#4DAF4A',  # Green
    'AMR': '#984EA3',  # Purple
    'SAS': '#FF7F00'   # Orange
}

# Ancestry colors for ADMIXTURE plots (reuse from super pop colors)
ANCESTRY_COLORS = list(SUPER_POP_COLORS.values())

# Define a distinct color palette for 26 populations
# Using a combination of qualitative palettes to ensure distinct colors
def get_population_colors(populations):
    """
    Generate a distinct color palette for 26 populations.
    
    Args:
        populations: List of population names
        
    Returns:
        Dictionary mapping population names to colors
    """
    # Use a combination of color palettes for maximum distinction
    n_pops = len(populations)
    
    # Combine multiple seaborn palettes
    colors = (
        sns.color_palette("tab10", 10) +
        sns.color_palette("Set2", 8) +
        sns.color_palette("Dark2", 8)
    )[:n_pops]
    
    return dict(zip(populations, colors))


def load_metadata(panel_file):
    """
    Load and parse the metadata panel file.
    
    The panel file is tab-separated with columns: sample, pop, super_pop, gender
    
    Args:
        panel_file: Path to the panel file
        
    Returns:
        DataFrame with metadata
    """
    metadata = pd.read_csv(
        panel_file,
        sep='\t',
        header=0
    )
    return metadata


def load_pca_data(eigenvec_file):
    """
    Load PCA eigenvector data from PLINK output.
    
    PLINK eigenvec files have no header. Format:
    FID IID PC1 PC2 PC3 ... PC20
    
    Args:
        eigenvec_file: Path to the .eigenvec file
        
    Returns:
        DataFrame with PCA data
    """
    # Define column names (FID, IID, then PC1-PC20)
    columns = ['FID', 'IID'] + [f'PC{i}' for i in range(1, 21)]
    
    pca_data = pd.read_csv(
        eigenvec_file,
        sep=r'\s+',
        header=None,
        names=columns
    )
    return pca_data


def load_admixture_data(q_file, fam_file):
    """
    Load ADMIXTURE Q matrix and associate with sample IDs.
    
    ADMIXTURE .Q files have no header and contain ancestry proportions.
    The order of individuals matches the .fam file.
    
    Args:
        q_file: Path to the .Q file
        fam_file: Path to the corresponding .fam file
        
    Returns:
        DataFrame with sample IDs and ancestry proportions
    """
    # Load Q matrix (no header)
    q_data = pd.read_csv(q_file, sep=r'\s+', header=None)
    
    # Get number of K (ancestral populations)
    k = q_data.shape[1]
    q_data.columns = [f'K{i+1}' for i in range(k)]
    
    # Load fam file to get sample IDs (no header)
    # FAM format: FID IID PID MID Sex Phenotype
    fam_data = pd.read_csv(
        fam_file,
        sep=r'\s+',
        header=None,
        names=['FID', 'IID', 'PID', 'MID', 'Sex', 'Phenotype']
    )
    
    # Add sample IDs to Q data
    q_data['IID'] = fam_data['IID'].values
    
    return q_data


def plot_pca_super_pop(pca_data, metadata, output_file):
    """
    Create PCA scatter plot colored by Super Population (5 groups).
    
    Plot 1: High-level view showing continental population structure.
    
    Args:
        pca_data: DataFrame with PCA results
        metadata: DataFrame with sample metadata
        output_file: Path to save the plot
    """
    # Merge PCA data with metadata on sample ID
    merged = pca_data.merge(
        metadata,
        left_on='IID',
        right_on='sample',
        how='left'
    )
    
    # Create figure
    plt.figure(figsize=(10, 8))
    
    # Plot each super population using the constant color dictionary
    for super_pop in SUPER_POP_COLORS:
        subset = merged[merged['super_pop'] == super_pop]
        plt.scatter(
            subset['PC1'],
            subset['PC2'],
            c=SUPER_POP_COLORS[super_pop],
            label=super_pop,
            alpha=0.7,
            s=20
        )
    
    plt.xlabel('PC1', fontsize=12)
    plt.ylabel('PC2', fontsize=12)
    plt.title('PCA of 1000 Genomes Chromosome 22 Data\n(Colored by Super Population)', fontsize=14)
    plt.legend(title='Super Population', loc='best')
    plt.tight_layout()
    
    # Save plot
    plt.savefig(output_file, dpi=300, bbox_inches='tight')
    plt.close()
    print(f"PCA (Super Population) plot saved to: {output_file}")


def plot_pca_detailed_pop(pca_data, metadata, output_file):
    """
    Create PCA scatter plot colored by Detailed Population (26 populations).
    
    Plot 2: Detailed view showing fine-scale population structure.
    Uses distinct colors and places legend outside to avoid covering data.
    
    Args:
        pca_data: DataFrame with PCA results
        metadata: DataFrame with sample metadata
        output_file: Path to save the plot
    """
    # Merge PCA data with metadata on sample ID
    merged = pca_data.merge(
        metadata,
        left_on='IID',
        right_on='sample',
        how='left'
    )
    
    # Get unique populations sorted by super_pop for grouping in legend
    merged_sorted = merged.sort_values(['super_pop', 'pop'])
    populations = merged_sorted['pop'].unique()
    
    # Generate color palette for 26 populations
    pop_colors = get_population_colors(populations)
    
    # Create figure with extra space for legend
    fig, ax = plt.subplots(figsize=(14, 10))
    
    # Define markers for different super populations to add visual distinction
    super_pop_markers = {
        'AFR': 'o',  # Circle
        'EUR': 's',  # Square
        'EAS': '^',  # Triangle up
        'AMR': 'D',  # Diamond
        'SAS': 'v'   # Triangle down
    }
    
    # Plot each population
    for pop in populations:
        subset = merged[merged['pop'] == pop]
        super_pop = subset['super_pop'].iloc[0]
        marker = super_pop_markers.get(super_pop, 'o')
        
        ax.scatter(
            subset['PC1'],
            subset['PC2'],
            c=[pop_colors[pop]],
            label=f"{pop} ({super_pop})",
            alpha=0.7,
            s=25,
            marker=marker
        )
    
    ax.set_xlabel('PC1', fontsize=12)
    ax.set_ylabel('PC2', fontsize=12)
    ax.set_title('PCA of 1000 Genomes Chromosome 22 Data\n(Colored by 26 Detailed Populations)', fontsize=14)
    
    # Place legend outside the plot area
    ax.legend(
        title='Population (Super Pop)',
        loc='center left',
        bbox_to_anchor=(1.02, 0.5),
        fontsize=8,
        ncol=1,
        framealpha=0.9
    )
    
    plt.tight_layout()
    
    # Save plot with extra space for legend
    plt.savefig(output_file, dpi=300, bbox_inches='tight')
    plt.close()
    print(f"PCA (Detailed Population) plot saved to: {output_file}")


def plot_admixture_sorted(q_data, metadata, output_file):
    """
    Create ADMIXTURE stacked bar plot for K=5, sorted by super_pop and pop.
    
    Plot 3: Individuals are sorted first by super_pop, then by pop within
    each super-population for organized visualization.
    X-axis is labeled with super_pop names to show continental boundaries.
    
    Args:
        q_data: DataFrame with ancestry proportions and sample IDs
        metadata: DataFrame with sample metadata
        output_file: Path to save the plot
    """
    # Merge with metadata
    merged = q_data.merge(
        metadata,
        left_on='IID',
        right_on='sample',
        how='left'
    )
    
    # Sort by super_pop and then pop for better visualization
    # Define custom order for super populations
    super_pop_order = ['AFR', 'EUR', 'EAS', 'SAS', 'AMR']
    merged['super_pop_order'] = merged['super_pop'].map(
        {sp: i for i, sp in enumerate(super_pop_order)}
    )
    merged = merged.sort_values(['super_pop_order', 'pop', 'IID'])
    merged = merged.reset_index(drop=True)
    
    # Get ancestry columns
    k_columns = [col for col in merged.columns if col.startswith('K')]
    
    # Create figure
    fig, ax = plt.subplots(figsize=(20, 6))
    
    # Create stacked bar chart
    n_individuals = len(merged)
    x = np.arange(n_individuals)
    
    bottom = np.zeros(n_individuals)
    for i, k_col in enumerate(k_columns):
        ax.bar(
            x,
            merged[k_col],
            bottom=bottom,
            color=ANCESTRY_COLORS[i % len(ANCESTRY_COLORS)],
            width=1.0,
            label=f'Ancestry {i+1}',
            edgecolor='none'
        )
        bottom = bottom + merged[k_col].values
    
    # Add vertical lines and labels for super populations
    tick_positions = []
    tick_labels = []
    prev_end = -1
    
    for super_pop in super_pop_order:
        pop_mask = merged['super_pop'] == super_pop
        if pop_mask.sum() > 0:
            pop_indices = merged[pop_mask].index
            start = pop_indices.min()
            end = pop_indices.max()
            mid = (start + end) / 2
            tick_positions.append(mid)
            tick_labels.append(super_pop)
            
            # Add vertical line at population boundary
            if prev_end >= 0:
                ax.axvline(x=start - 0.5, color='black', linewidth=1.0)
            prev_end = end
    
    # Configure axes
    ax.set_xticks(tick_positions)
    ax.set_xticklabels(tick_labels, fontsize=12, fontweight='bold')
    
    ax.set_xlim(-0.5, n_individuals - 0.5)
    ax.set_ylim(0, 1)
    ax.set_xlabel('Super Population', fontsize=14)
    ax.set_ylabel('Ancestry Proportion', fontsize=12)
    ax.set_title('ADMIXTURE Analysis (K=5) - 1000 Genomes Chromosome 22\n(Sorted by Super Population and Population)', fontsize=14)
    
    # Add legend outside plot
    ax.legend(
        loc='upper left',
        bbox_to_anchor=(1.01, 1),
        framealpha=0.9
    )
    
    # Remove top and right spines for cleaner look
    ax.spines['top'].set_visible(False)
    ax.spines['right'].set_visible(False)
    
    plt.tight_layout()
    
    # Save plot
    plt.savefig(output_file, dpi=300, bbox_inches='tight')
    plt.close()
    print(f"ADMIXTURE (sorted) plot saved to: {output_file}")


def main():
    """Main function to generate all plots."""
    # Define file paths
    results_dir = 'results'
    panel_file = 'integrated_call_samples_v3.20130502.ALL.panel'
    eigenvec_file = os.path.join(results_dir, 'chr22_pca.eigenvec')
    q_file = os.path.join(results_dir, 'chr22_pruned.5.Q')
    fam_file = os.path.join(results_dir, 'chr22_pruned.fam')
    
    # Output files (updated names)
    pca_super_pop_output = os.path.join(results_dir, 'pca_super_pop.png')
    pca_detailed_output = os.path.join(results_dir, 'pca_detailed_pop.png')
    admixture_output = os.path.join(results_dir, 'admixture_k5_sorted.png')
    
    # Check if input files exist
    if not os.path.exists(panel_file):
        print(f"ERROR: Panel file not found: {panel_file}")
        sys.exit(1)
    
    if not os.path.exists(eigenvec_file):
        print(f"ERROR: PCA eigenvec file not found: {eigenvec_file}")
        sys.exit(1)
    
    if not os.path.exists(q_file):
        print(f"ERROR: ADMIXTURE Q file not found: {q_file}")
        sys.exit(1)
    
    if not os.path.exists(fam_file):
        print(f"ERROR: FAM file not found: {fam_file}")
        sys.exit(1)
    
    print("=" * 60)
    print("Population Genetics Visualization Script")
    print("=" * 60)
    print("\nLoading data files...")
    
    # Load metadata
    metadata = load_metadata(panel_file)
    print(f"  - Loaded metadata for {len(metadata)} samples")
    print(f"  - Super populations: {metadata['super_pop'].nunique()} groups")
    print(f"  - Detailed populations: {metadata['pop'].nunique()} groups")
    
    # Load PCA data
    pca_data = load_pca_data(eigenvec_file)
    print(f"  - Loaded PCA data for {len(pca_data)} samples")
    
    # Load ADMIXTURE data
    q_data = load_admixture_data(q_file, fam_file)
    print(f"  - Loaded ADMIXTURE data for {len(q_data)} samples")
    
    # Plot 1: PCA by Super Population
    print("\n" + "-" * 60)
    print("Plot 1: PCA by Super Population (High Level)")
    print("-" * 60)
    plot_pca_super_pop(pca_data, metadata, pca_super_pop_output)
    
    # Plot 2: PCA by Detailed Population
    print("\n" + "-" * 60)
    print("Plot 2: PCA by Detailed Population (26 populations)")
    print("-" * 60)
    plot_pca_detailed_pop(pca_data, metadata, pca_detailed_output)
    
    # Plot 3: ADMIXTURE Bar Plot (Sorted)
    print("\n" + "-" * 60)
    print("Plot 3: ADMIXTURE Bar Plot (K=5, Sorted)")
    print("-" * 60)
    plot_admixture_sorted(q_data, metadata, admixture_output)
    
    print("\n" + "=" * 60)
    print("Visualization complete!")
    print("=" * 60)
    print("\nOutput files:")
    print(f"  1. {pca_super_pop_output}")
    print(f"  2. {pca_detailed_output}")
    print(f"  3. {admixture_output}")


if __name__ == '__main__':
    main()
